def get_fact_by_id(fact_id):
    """Получить факт по его id."""
    for fact in FACTS:
        if fact["id"] == fact_id:
            return fact
    return None


def get_total_facts():
    """Вернуть общее количество фактов."""
    return len(FACTS)


def format_progress_bar(current, total, filled_icon="💎", empty_icon="🤍"):
    """Создать визуальный прогресс-бар."""
    filled = filled_icon * current
    empty = empty_icon * (total - current)
    return f"{filled}{empty}"


def get_fact_step_text(fact, step_index):
    """Получить текст конкретного шага факта."""
    if step_index < len(fact["steps"]):
        return fact["steps"][step_index]
    return None


def is_last_step(fact, step_index):
    """Проверить, является ли шаг последним."""
    return step_index >= len(fact["steps"]) - 1